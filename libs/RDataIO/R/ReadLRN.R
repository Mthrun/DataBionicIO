ReadLRN=function(FileName, InDirectory=getwd(), Verbose=TRUE) {
#  V = ReadLRN(FileName,InDirectory);
#  Key = V$Key
#  Data = V$Data
#  DataDefined = V$DataDefined
#  Comment = V$Comments
#  Header = V$Header
#   
# INPUT
# FileName      FileName of *.lrn file
# OPTIONAL
# InDirectory   Directory where *.lrn file is, default: current dir
#
# OUTPUT list with:
# Key (1:n)       Numeric vector of whole-number keys within +/- 2^53; invalid file keys become NA
# Data (1:n, 1:d) Numeric matrix
# Header (1:d)    Column names of the file (excluding "Key")
# DataDefined (1:d+1)  Data types of the columns (including "Key")
# Comments      String of the Comment in the file (does not include autogenerated part in the write process)
#
# DETAILS
# Spaces, commas, and semicolons in header labels are removed with a warning.
# Tabs in the file separate columns. Text values are not subject to header filtering.
# Files without a generation tag, or with version 1.0, can use old key names and positions.
# Type 9 selects the key column. If it is absent, the reader warns and generates keys 1:n.
# Returned DataDefined puts the key type first. The data columns keep their original order.
# Version 2.0 files keep the current header requirements. Legacy support is read-only.
#
# author: Luca Brinkmann (IAP-GmbH Intelligent Analytics Projects) 05/2024
# SPDX-License-Identifier: AGPL-3.0-only
# Additional permission: see MATLAB-EXCEPTION.txt.
# Reimplemented from the original R function ReadLRN by Michael Thrun.

  if(!is.character(FileName)) {
    stop("FileName has to be character/string")
  } else {
    invalid_chars = "[/\\\\:*?\"<>|]"
    if (grepl(invalid_chars, FileName)) {
      stop(paste("FileName", FileName, "contains invalid symbol. The symbols / \\ : * ? \" < > | are invalid for a file name."))
    }
  }
  
  InDirectory = normalizePath(InDirectory, mustWork = FALSE)
  path = file.path(InDirectory, FileName)
  
  res = read_lrn(path, Verbose)
  
  return(list(Key = res$Key, Data = res$Data, Header = res$Header,
              DataDefined = res$DataDefined, Comments = if(is.null(res$Comments)) "" else res$Comments))
}
