ReadDates <- function(FileName, InDirectory = getwd(), Verbose = TRUE) {
  #  V = ReadDates(FileName,InDirectory);
  #  Key = V$Key
  #  Time = V$Time
  #  Data = V$Data
  #  Comment = V$Comments
  #  Timezone = V$Timezone
  #   
  # INPUT
  # FileName      FileName of *.dts or *.csv file
  # OPTIONAL
  # InDirectory   Directory where *.dts or *.csv file is, default: current dir
  #
  # OUTPUT list with:
  # Key (1:n)     Numeric vector of whole-number keys within +/- 2^53; invalid file keys become NA
  # Time (1:n)    Vector of POSIX Dates/Datetimes
  # Data (1:n, 1:d) matrix
  # Timezone      Timezone as String
  # Comments      String of the Comment in the file (does not include autogenerated part in the write process)
  #
  # LIMITATIONS
  # Numeric TZ_DST abbreviations (e.g. +11, +1030, -02) are not supported for DATES round trips.
  # Affected zones include Australia/Lord_Howe (Australia/LHI), Pacific/Chatham (NZ-CHAT),
  # and historical DST dates in America/Sao_Paulo (Brazil/East). This list is not exhaustive;
  # support depends on the abbreviations for the actual dates, not only the zone name.
  # Use UTC for these timestamps when writing; date-only values do not need TZ_DST.
  #
  # author: Luca Brinkmann 05/2024
  # SPDX-License-Identifier: AGPL-3.0-only
  # Additional permission: see MATLAB-EXCEPTION.txt.
  
  DEBUG = FALSE

  if(!is.character(FileName)) {
    stop("FileName has to be character/string")
  } else {
    invalid_chars = "[/\\\\:*?\"<>|]"
    if (grepl(invalid_chars, FileName)) {
      stop(paste("FileName", FileName, "contains invalid symbol. The symbols / \\ : * ? \" < > | are invalid for a file name."))
    }
  }
  
  InDirectory = normalizePath(InDirectory, mustWork = TRUE)
  res = read_dates(file.path(InDirectory, FileName), Verbose)
  if (DEBUG) {
    print(res$Data)
  }
  strip_time = function(date) {
    # Convert DATES text to R dates or timestamps.
    #
    # INPUT
    # date          Character vector of dates or timestamps.
    # res$Timezone  Time zone from the enclosing ReadDates call.
    # res$DST       Optional DST abbreviations from the same call.
    #
    # OUTPUT
    # Date vector for date-only input; otherwise a POSIXct vector.
    # Invalid DST matches become NA and cause a warning.
    # SPDX-License-Identifier: AGPL-3.0-only
    # Additional permission: see MATLAB-EXCEPTION.txt.
    maxDateLen = max(nchar(date))
    if(maxDateLen > 10) {
      
      # The C++ reader validates ISO fields; parse them with base R.
      wall_strings = date
      date_only = !is.na(date) & nchar(date) == 10L
      wall_strings[date_only] = paste0(date[date_only], " 00:00:00")
      wall_time = as.POSIXct(wall_strings, format = "%Y-%m-%d %H:%M:%OS", tz = "GMT")
      psx = lubridate::force_tz(wall_time, tzone = res$Timezone, roll_dst = c("NA", "post"))
      if(!is.null(res$DST)) {
        # Fixed 2024 probes rejected historical DST and guessed repeated autumn hours.
        # Match the stored abbreviation to both candidates under the actual date's rules.
        earlier = lubridate::force_tz(wall_time, tzone = res$Timezone, roll_dst = c("NA", "pre"))
        # Compare timestamp abbreviations with the stored DST markers.
        #
        # INPUT
        # x             POSIXct candidate timestamps.
        # res$DST       Stored DST abbreviations in the enclosing function.
        # res$Timezone  Time zone used for abbreviation formatting.
        #
        # OUTPUT
        # Logical vector; TRUE identifies a non-missing matching abbreviation.
        # SPDX-License-Identifier: AGPL-3.0-only
        # Additional permission: see MATLAB-EXCEPTION.txt.
        matches = function(x) !is.na(x) & !is.na(res$DST) &
          format(x, "%Z", tz = res$Timezone) == res$DST
        before = matches(earlier)
        after = matches(psx)
        invalid = !is.na(wall_time) & (!(before | after) |
          (before & after & earlier != psx))
        psx[before & !after] = earlier[before & !after]
        # Keep malformed rows, but do not invent an instant for an inconsistent DST marker.
        if(any(invalid)) {
          warning("DST information does not uniquely match the timestamp and timezone; returning NA for affected times")
          psx[invalid] = NA
        }
      }
      return(psx)
    } else {
      dates = as.Date(date, format = "%Y-%m-%d")
      return(dates)
    }
  }
  res$Time = strip_time(res$Time)
  if(!is.null(res$DST)) res$DST = NULL
  return(res)
}
