ReadCLS = function(FileName,InDirectory=getwd(), Verbose = TRUE){
#  V = ReadCLS(FileName,InDirectory);
#  Key = V$Key
#  CLS = V$Cls
#  Comment = V$Comments
#  UniqueClasses = V$UniqueClasses
#   
# INPUT
# FileName      FileName of *.cls file
# OPTIONAL
# InDirectory   Directory where *.cls file is, default: current dir
#
# OUTPUT list with:
# Key (1:n)     Numeric vector of whole-number keys within +/- 2^53; invalid file keys become NA
# Cls (1:n)     Integer vector of class values (can contain NaN)
# UniqueClasses Integer vector of the unique classes
# Comments      String of the Comment in the file (does not include autogenerated part in the write process)
#
# DETAILS
# Files without a generation tag, or with version 1.0, can use spaces between numeric fields.
# They can omit the row-count header; the reader warns and keeps all data rows.
# CLS colour metadata is ignored. Version 2.0 files keep the current header requirements.
# Legacy support is read-only.
#
# author: Luca Brinkmann (IAP-GmbH Intelligent Analytics Projects) 05/2024
# SPDX-License-Identifier: AGPL-3.0-only
# Additional permission: see MATLAB-EXCEPTION.txt.
# Reimplemented from the original R function ReadCLS by Michael Thrun.

  if(!is.character(FileName)) {
    stop("FileName has to be character/string")
  } else {
    invalid_chars = "[/\\\\:*?\"<>|]"
    if (grepl(invalid_chars, FileName)) {
      stop(paste("FileName", FileName, "contains invalid symbol. The symbols / \\ : * ? \" < > | are invalid for a file name."))
    }
  }
  
  InDirectory = normalizePath(InDirectory, mustWork = FALSE)
  path = file.path(InDirectory, FileName)
  
  result = read_cls(path, Verbose)
  
  return(list(Key = result$Key, Cls = result$Cls, UniqueClasses = result$UniqueClasses,
              Comments = if(is.null(result$Comments)) "" else result$Comments))
}
