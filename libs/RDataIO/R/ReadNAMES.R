ReadNAMES = function(FileName,InDirectory=getwd(),Verbose=TRUE){
#  V = ReadNAMES(FileName,InDirectory);
#  Key = V$Key
#  Names = V$Names
#  FurtherTexts = V$FurtherTexts
#  Comments = V$Comments
#  Header = V$Header
#   
# INPUT
# FileName      FileName of *.names file
# OPTIONAL
# InDirectory   Directory where *.names file is, default: current dir
#
# OUTPUT list with:
# Key (1:n)               Numeric vector of whole-number keys within +/- 2^53; invalid file keys become NA
# Names (1:n)             Character vector of the names column (second column after key)
# FurtherTexts (1:n, 1:d) Character matrix
# Header (1:d+1)          Column names of the file (excluding "Key")
# Comments                String of the Comment in the file (does not include autogenerated part in the write process)
#
# DETAILS
# Spaces, commas, and semicolons in header labels are removed with a warning.
# Tabs in the file separate columns. Text values are not subject to header filtering.
# Files without a generation tag, or with version 1.0, can omit the column count.
# If both the count and column names are absent, the first data row sets the width.
# Later rows cannot add columns. Version 2.0 files require the current header.
# Legacy support is read-only.
#
# author: Luca Brinkmann (IAP-GmbH Intelligent Analytics Projects) 05/2024
# SPDX-License-Identifier: AGPL-3.0-only
# Additional permission: see MATLAB-EXCEPTION.txt.
# Reimplemented from the original R function ReadNAMES by Michael Thrun.

  if(!is.character(FileName)) {
    stop("FileName has to be character/string")
  } else {
    invalid_chars = "[/\\\\:*?\"<>|]"
    if (grepl(invalid_chars, FileName)) {
      stop(paste("FileName", FileName, "contains invalid symbol. The symbols / \\ : * ? \" < > | are invalid for a file name."))
    }
  }
  
  InDirectory = normalizePath(InDirectory, mustWork = FALSE)
  path = file.path(InDirectory, FileName)
  
  result = read_names(path, Verbose)
  
  return (result)
}
