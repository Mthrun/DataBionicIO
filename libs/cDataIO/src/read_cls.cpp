		/**
		 * Read a CLS file through the shared core.
		 *
		 * INPUT
		 * path  Filesystem path.
		 * verbose  Select information messages; data warnings can remain active.
		 * output_stream  Destination stream for diagnostics.
		 *
		 * OUTPUT
		 * Tuple: keys, class values, unique classes, comments.
		 * Invalid keys use MISSING_KEY; invalid class cells use NaN.
		 * SPDX-License-Identifier: AGPL-3.0-only
		 * Additional permission: see MATLAB-EXCEPTION.txt.
		 */
		std::tuple<std::vector<Key>, std::vector<double>, std::vector<double>, std::string> _read_cls(std::string path, bool verbose, std::ostream& output_stream) {
			path = addext_checkext(path, "cls");
			std::ifstream stream = open_read(path);

			bool first_line = true;
			bool legacy_format = false;

			int N = -1;
			std::set<double> _unique_classes;
			std::vector<double> cls;
			std::vector<Key> keys;
			std::string comment = "";
			bool has_type = false;

			int row = 0;

			//int version_major = 1;
			//int version_minor = 0;

			bool has_nan = false;
			bool user_comment_ended = false;
			// The old loop built a stream for each row. Reuse it and reset its end-of-file state.
			std::stringstream vals;
			//bool has_cls_statistic = false;
			for (std::string line; getline(stream, line); ) {
				// handle CRLF
				if (!line.empty() && line.back() == '\r') {
					line.pop_back();
				}
				// Tab-only records carry missing cells and must retain their row.
				if (line.empty() || (line.find('\t') == std::string::npos && std::all_of(line.begin(), line.end(), isspace))) continue;

				if (first_line) {
					// Legacy entry point: parse the version before selecting old header rules.
					// The old substring lost the closing quote when the tag had no timestamp.
					legacy_format = legacy::is_legacy_format(line, "cls");
					const bool has_version = line.starts_with("#<?cls ");
					if (has_version) line.clear();

					if (verbose) {
						if (!has_version) {
							output_stream << "No version found; proceeding with reader version: 1.0!" << std::endl;
						}
						// Currently this output is not wanted anymore
						//else {
						//	output_stream << "Reader version: " << version_major << "." << version_minor << "!" << std::endl;
						//}
					}

					first_line = false;
				}

				std::string body_line = line;
				const auto start = line.find_first_not_of(" \t");
				if (start == std::string::npos) {
					// A tab-only data row has missing Key/Cls cells; do not drop it.
					if ((!has_type && !legacy_format) || line.find('\t') == std::string::npos) continue;
				} else {
					const auto end = line.find_last_not_of(" \t");
					const auto range = end - start + 1;
					line = line.substr(start, range);
				}


				if (line == "")
					continue;
				if (line.starts_with("#")) {
					// COMMENT
					line = line.substr(1);
					// End of user comment, beginn of autogenerated comment.
					if (line.starts_with("\tClass\tN\tPercent"))
						user_comment_ended = true;
					if(user_comment_ended == false) {
						std::size_t idx = line.find_first_not_of(" \t");
						// Blank comment lines yielded npos and threw; preserve their empty text safely.
						if (idx == std::string::npos) idx = line.size();
						if (comment == "") {
							comment += line.substr(idx);
						}
						else {
							comment += "\n" + line.substr(idx);
						}
					}
					continue;
				}
				else if (line.starts_with("%")) {
					// HEADER
					line = line.substr(1);
					std::size_t idx = line.find_first_not_of(" \t");
					line = line.substr(idx);

					if (N < 0) {
						N = std::stoi(line);
					}

					keys.reserve(N);

					has_type = true;
				} else {
					// Legacy entry point: accept old separators and an omitted row count.
					if (legacy_format) legacy::cls_row(body_line, has_type, output_stream);
					if (!has_type || first_line) {
						throw std::invalid_argument("A non-escaped line (#, %) was found before a header/type section was completed! Something seems to be wrong with the header section...");
					}

					// Retain malformed rows at the fixed Key/Cls width instead of misaligning vectors.
					vals.clear();
					vals.str(body_line);
					std::string val;
					int j = 0;
					double cls_value = std::numeric_limits<double>::quiet_NaN();
					bool invalid = false;
					while (std::getline(vals, val, '\t')) {
						if (j == 0) {
							// Keep a readable numeric prefix; warn if trailing characters were ignored.
							try {
								std::size_t consumed = 0;
								keys.push_back(parse_key_cell(val, &consumed));
								warn_numeric_suffix(val, consumed, output_stream);
							}
							catch (...) { keys.push_back(MISSING_KEY); invalid = true; }
						} else if (j == 1) {
							// Missing cells caused conversion exceptions; keep NaN and the same row warning directly.
							if (val.empty() || val == "NA") invalid = true;
							else try {
								std::size_t consumed = 0;
								double v = std::stod(val, &consumed);
								warn_numeric_suffix(val, consumed, output_stream);
								// Casting NaN/infinity/out-of-range doubles to int was undefined.
								if (!std::isnan(v) && (!std::isfinite(v) || v < INT_MIN || v > INT_MAX || std::trunc(v) != v))
									invalid = true;
								else cls_value = v;
							} catch (...) { invalid = true; }
						}
						++j;
					}
					if (!body_line.empty() && body_line.back() == '\t') { ++j; invalid = true; }
					if (j != 2 || invalid)
						output_stream << "WARNING: CLS row " << row + 1 << " has incorrect fields. The reader uses missing keys or NaN values. The reader ignores additional fields." << std::endl;
					cls.push_back(cls_value);
					if (!std::isnan(cls_value)) _unique_classes.insert(cls_value);
					row++;
				}
			}
			std::vector<double> unique_classes(_unique_classes.begin(), _unique_classes.end());

			if (N >= 0 && row != N) {
				// Keep actual rows when the recorded count is stale.
				output_stream << "WARNING: CLS header declares " << N << " rows. The reader keeps all " << row << " actual rows." << std::endl;
			}

			// The local vectors are finished; transfer them without full-column copies.
			return { std::move(keys), std::move(cls), std::move(unique_classes), std::move(comment) };
		}

		/**
		 * Read a CLS file through the shared core.
		 *
		 * INPUT
		 * path  Filesystem path.
		 * verbose  Select information messages; data warnings can remain active.
		 * output_stream  Destination stream for diagnostics.
		 *
		 * OUTPUT
		 * Tuple: keys, class values, unique classes, comments.
		 * Invalid keys use MISSING_KEY; invalid class cells use NaN.
		 * SPDX-License-Identifier: AGPL-3.0-only
		 * Additional permission: see MATLAB-EXCEPTION.txt.
		 */
		std::tuple<std::vector<Key>, std::vector<double>, std::vector<double>, std::string> read_cls(std::string path, bool verbose, std::ostream& output_stream) {
			return(_read_cls(path, verbose, output_stream));
		}


